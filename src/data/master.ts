// неразрывный пробел после коротких предлогов и союзов, чтобы они не висели в конце строки
const NB = /(^|[\s(«])([вВиИсСкКоОуУаАяЯ]|на|На|не|Не|по|По|за|За|до|До|от|От|из|Из|для|Для|без|при|про|над|под|что|как|или|но|же) +/g;
function nb<T>(v: T): T {
  if (typeof v === 'string') {
    let s: string = v;
    for (let i = 0; i < 3; i++) s = s.replace(NB, '$1$2\u00a0');
    s = s.replace(/(\d) (лет|года|год|минут|часа|встреч|оценок)/g, '$1\u00a0$2');
    s = s.replace(/(\d)-(\d)/g, '$1\u2011$2');
    return s as T;
  }
  if (Array.isArray(v)) return v.map(nb) as T;
  if (v && typeof v === 'object') {
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, k === 'slug' || /href|url|vk|telegram|whatsapp|max|gis/i.test(k) ? x : nb(x)])) as T;
  }
  return v;
}

